DROP VIEW IF EXISTS accepted_paper_schedule;
DROP TABLE IF EXISTS review CASCADE;
DROP TABLE IF EXISTS paper_version CASCADE;
DROP TABLE IF EXISTS paper_author CASCADE;
DROP TABLE IF EXISTS paper_keyword CASCADE;
DROP TABLE IF EXISTS paper CASCADE;
DROP TABLE IF EXISTS conference_session CASCADE;
DROP TABLE IF EXISTS track CASCADE;
DROP TABLE IF EXISTS conference_reviewer CASCADE;
DROP TABLE IF EXISTS conference_host CASCADE;
DROP TABLE IF EXISTS conference CASCADE;
DROP TABLE IF EXISTS reviewer_expertise CASCADE;
DROP TABLE IF EXISTS reviewer CASCADE;
DROP TABLE IF EXISTS author_research_area CASCADE;
DROP TABLE IF EXISTS author CASCADE;
DROP TABLE IF EXISTS app_user CASCADE;

CREATE TABLE app_user (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    given_name VARCHAR(50) NOT NULL,
    surname VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL,
    affiliation VARCHAR(150) NOT NULL,
    country VARCHAR(60) NOT NULL,
    phone_number VARCHAR(20) NOT NULL,
    CONSTRAINT uq_user_email UNIQUE (email),
    CONSTRAINT chk_user_email CHECK (email ~ '^[^@ ]+@[^@ ]+$')
);

CREATE TABLE author (
    author_id INTEGER PRIMARY KEY REFERENCES app_user(user_id) ON DELETE CASCADE,
    orcid CHAR(19) UNIQUE,
    CONSTRAINT chk_orcid CHECK (orcid ~ '^[0-9]{4}-[0-9]{4}-[0-9]{4}-[0-9]{3}[0-9X]$')
);

CREATE TABLE author_research_area (
    author_id INTEGER REFERENCES author(author_id) ON DELETE CASCADE,
    area_label VARCHAR(80),
    PRIMARY KEY (author_id, area_label)
);

CREATE TABLE reviewer (
    reviewer_id INTEGER PRIMARY KEY REFERENCES app_user(user_id) ON DELETE CASCADE,
    years_experience INTEGER NOT NULL,
    CONSTRAINT chk_experience CHECK (years_experience >= 0)
);

CREATE TABLE reviewer_expertise (
    reviewer_id INTEGER REFERENCES reviewer(reviewer_id) ON DELETE CASCADE,
    area_label VARCHAR(80),
    PRIMARY KEY (reviewer_id, area_label)
);

CREATE TABLE conference (
    conference_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    acronym VARCHAR(20) NOT NULL UNIQUE,
    description TEXT NOT NULL,
    city VARCHAR(60) NOT NULL,
    country VARCHAR(60) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    submission_deadline DATE NOT NULL,
    review_deadline DATE NOT NULL,
    CONSTRAINT chk_conf_dates CHECK (end_date >= start_date),
    CONSTRAINT chk_conf_deadlines CHECK (review_deadline >= submission_deadline)
);

CREATE TABLE conference_host (
    conference_id INTEGER REFERENCES conference(conference_id) ON DELETE CASCADE,
    host_name VARCHAR(150),
    PRIMARY KEY (conference_id, host_name)
);

CREATE TABLE conference_reviewer (
    conference_id INTEGER REFERENCES conference(conference_id) ON DELETE CASCADE,
    reviewer_id INTEGER REFERENCES reviewer(reviewer_id) ON DELETE CASCADE,
    PRIMARY KEY (conference_id, reviewer_id)
);

CREATE TABLE track (
    track_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conference_id INTEGER NOT NULL REFERENCES conference(conference_id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    description TEXT NOT NULL,
    research_area VARCHAR(80) NOT NULL,
    coordinator_id INTEGER NOT NULL REFERENCES reviewer(reviewer_id),
    UNIQUE (conference_id, name),
    CONSTRAINT fk_coordinator_in_pool FOREIGN KEY (conference_id, coordinator_id)
        REFERENCES conference_reviewer(conference_id, reviewer_id)
);

CREATE TABLE conference_session (
    session_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conference_id INTEGER NOT NULL REFERENCES conference(conference_id) ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL,
    session_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    room_label VARCHAR(30) NOT NULL,
    chair_id INTEGER NOT NULL REFERENCES reviewer(reviewer_id),
    CONSTRAINT fk_chair_in_pool FOREIGN KEY (conference_id, chair_id)
        REFERENCES conference_reviewer(conference_id, reviewer_id),
    CONSTRAINT chk_session_times CHECK (end_time > start_time)
);

CREATE TABLE paper (
    paper_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id INTEGER NOT NULL REFERENCES track(track_id) ON DELETE RESTRICT,
    title VARCHAR(250) NOT NULL,
    abstract TEXT NOT NULL,
    submission_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'submitted',
    session_id INTEGER REFERENCES conference_session(session_id) ON DELETE SET NULL,
    CONSTRAINT chk_paper_status CHECK (status IN ('submitted', 'under review', 'accepted', 'rejected', 'withdrawn')),
    CONSTRAINT chk_session_only_accepted CHECK (session_id IS NULL OR status = 'accepted')
);

CREATE TABLE paper_keyword (
    paper_id INTEGER REFERENCES paper(paper_id) ON DELETE CASCADE,
    keyword VARCHAR(80),
    PRIMARY KEY (paper_id, keyword)
);

CREATE TABLE paper_author (
    paper_id INTEGER REFERENCES paper(paper_id) ON DELETE CASCADE,
    author_id INTEGER REFERENCES author(author_id) ON DELETE RESTRICT,
    author_position INTEGER NOT NULL,
    is_corresponding BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (paper_id, author_id),
    CONSTRAINT uq_author_position UNIQUE (paper_id, author_position),
    CONSTRAINT chk_author_position CHECK (author_position > 0)
);

CREATE UNIQUE INDEX uq_one_corresponding_author ON paper_author (paper_id) WHERE is_corresponding;

CREATE TABLE paper_version (
    paper_id INTEGER REFERENCES paper(paper_id) ON DELETE CASCADE,
    version_no INTEGER,
    file_location VARCHAR(255) NOT NULL,
    uploaded_at TIMESTAMP NOT NULL,
    change_note TEXT,
    PRIMARY KEY (paper_id, version_no),
    CONSTRAINT chk_version_no CHECK (version_no > 0)
);

CREATE TABLE review (
    review_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paper_id INTEGER NOT NULL REFERENCES paper(paper_id) ON DELETE CASCADE,
    reviewer_id INTEGER NOT NULL REFERENCES reviewer(reviewer_id) ON DELETE RESTRICT,
    overall_score INTEGER NOT NULL,
    recommendation VARCHAR(10) NOT NULL,
    comments_for_authors TEXT NOT NULL,
    confidential_comments TEXT,
    review_submission_date DATE NOT NULL,
    CONSTRAINT uq_review_paper_reviewer UNIQUE (paper_id, reviewer_id),
    CONSTRAINT chk_score CHECK (overall_score BETWEEN 1 AND 5),
    CONSTRAINT chk_recommendation CHECK (recommendation IN ('accept', 'reject'))
);
